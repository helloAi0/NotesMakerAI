import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' }).catch(()=>chromium.launch());
const pg = await b.newPage({ viewport: { width: 1400, height: 900 } });
const errs=[]; pg.on('pageerror', e=>errs.push(e.message));
const check=(n,ok)=>console.log(ok?'PASS':'FAIL',n);
await pg.goto('http://localhost:5199/'); await pg.waitForTimeout(600);
// --- Visuals Studio direct
await pg.click('nav button:has-text("Visuals Studio")'); await pg.waitForTimeout(300);
check('library header count', await pg.isVisible('text=/\\d+ Functional Simulations/'));
await pg.click('button:has-text("Curriculum Coverage")');
check('coverage summary', await pg.isVisible('text=/topics have a working simulation/'));
const nPlanned = await pg.locator('text=PLANNED').count(); check('planned topics shown honestly ('+nPlanned+')', nPlanned>5);
await pg.selectOption('select >> nth=2', 'planned').catch(()=>{});
await pg.selectOption('xpath=(//select)[3]', 'working');
await pg.fill('input[placeholder="Search topics…"]','Kalman');
check('search finds Kalman only', (await pg.locator('text=WORKING').count())===1 && await pg.isVisible('button:has-text("Kalman")'));
await pg.click('button:has-text("Kalman")'); await pg.waitForTimeout(800);
check('sim opened from coverage', await pg.isVisible('text=Kalman Filter'));
check('Back to Simulation Library visible', await pg.isVisible('button:has-text("Back to Simulation Library")'));
const cv = await pg.locator('canvas').first().evaluate(c=>c.width>100);
check('canvas present', cv);
await pg.screenshot({path:'/tmp/e2e_sim.png'});
await pg.click('button:has-text("Back to Simulation Library")'); await pg.waitForTimeout(300);
check('back to simulation home', await pg.isVisible('text=/Functional Simulations/'));
// --- From notebook
await pg.click('nav button:has-text("Digital Notebook")'); await pg.waitForTimeout(500);
await pg.click('button:has-text("Open Visuals Studio")').catch(async()=>{ await pg.click('button:has-text("Visuals")'); });
await pg.waitForTimeout(500);
check('return to notebook button in studio', await pg.isVisible('button:has-text("Return to Notebook")'));
await pg.fill('input[placeholder*="earch"] >> nth=-1','Projectile').catch(()=>{});
await pg.locator('text=Projectile').first().click().catch(()=>{}); await pg.waitForTimeout(600);
check('Back to Notebook inside sim', await pg.isVisible('button:has-text("Back to Notebook")'));
await pg.click('button:has-text("Add to Notebook")'); await pg.waitForTimeout(400);
await pg.screenshot({path:'/tmp/e2e_add.png'});
console.log('errors:', errs.slice(0,5));
await b.close();
